class Ejercicio_1 {
    fun ejecutar() {
        print("Introduce una cadena: ")
        var a = 15.0
        var b = 4.0

        println("Suma:  " + "${a + b}")
        println("Resta:  " + "${a - b}")
        println("Multiplica:  " + "${a * b}")
        println("Division: " + "${a / b}")
        println("Modulo: " +  "${a % b}")
    }
}